# calculadora básica 

n1 = float(input('Por favor, digite um valor: '))
n2 = float (input('Por favor, digite outro valor: '))
soma = n1 + n2
div_inteira = n1 // n2
exponenciacao = n1 ** n2
resto_div = n1 % n2
print(f'A soma é  {soma} e a divisão serão {div_inteira}.\n Já a exponenciação {exponenciacao} e o resto da divisão também serão {resto_div}')