#operadores aritmétricos

adicao = 10 + 10
print('adição:', adicao)

subtracao = 10 - 5
print('subtração:', subtracao)  

multiplicacao = 10 * 10
print ('multiplicação:', multiplicacao)

divisao = 10/3 # retorna numeros float e retorna as casas decimais. 
print('divisão:', divisao)

divisão_inteira = 10 // 3 # essa divisão não retorna as casas decimais 
print('divisão_ inteira:', divisão_inteira)

exponenciacao = 2**10 # dois elevado a 10 
print('exponenciação', exponenciacao)

modulo = 25 % 5 # resto da divisão
print('módulo',modulo)

# é possivel saber se um número é multiplo por outro 
print(10 % 8 == 0 ) # se for multriplo, o resultado é true ou false
print(10 % 2 == 0) 
