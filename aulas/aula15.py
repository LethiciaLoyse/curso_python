# mini revisão de if, elif e else
# condicoes false são chegadas, mas não são executadas. 

condicao1 = False
condicao2 = True
condicao3 = True
condicao4 = False

if condicao1:
    print('Código para 1')
elif condicao2:
    print('Código para 2')
elif condicao3:
    print('Código para a 3')
elif condicao4:
    print('Código para a 4')
else:
    print('Nenhuma condição foi solicitada')

