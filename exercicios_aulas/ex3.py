# exercicio de comparação e if 
valor1 = input('Digite o 1° valor: ')
valor2 = input('Digite o 2° valor: ')

if valor1 >= valor2:
    print('O 1° valor é maior que o 2° valor.')
elif valor2 >= valor1:
    print('O 2° segundo valor é maior que o 1° valor.')
else:
    print('Você não digitou nenhum valor. ')

